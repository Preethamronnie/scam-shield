def spoken_summary(verdict: str, language: str) -> str:
    """A short, fixed summary of the verdict in the chosen language."""
    p = PHRASES.get(language, PHRASES["English"])
    parts = [p[verdict]]
    if verdict in (SCAM, CAREFUL):
        parts += [p["dont"], p["paid"]]
    elif verdict == UNSURE:
        parts += [p["dont"], p["check"]]
    return " ".join(parts)


